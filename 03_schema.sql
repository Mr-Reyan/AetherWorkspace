-- AI SaaS Workspace: database schema (PostgreSQL 14+ with pgvector)
-- Derived by hand from the Django models (authen, workspace, documents).
-- Table/column names match Django's generated names so this file and the
-- migrations describe the same database.
--
-- PART 1 mirrors what the code defines today (see models.py files).
-- PART 2 is PROPOSED hardening that is NOT in the current migrations.
--
-- VERIFY BEFORE SUBMITTING: this file was written without running it against
-- a database. Apply it to an empty scratch DB, then compare with
--   pg_dump --schema-only <your migrated db>
-- and fix any differences.
--
-- NOTE on FK actions: Django enforces on_delete (CASCADE/PROTECT) in Python
-- and emits plain FKs. Here they are written as real ON DELETE clauses that
-- express the same intent (PROTECT -> RESTRICT).

CREATE EXTENSION IF NOT EXISTS vector;

-- ---------------------------------------------------------------- PART 1 --

CREATE TABLE authen_user (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password     VARCHAR(128) NOT NULL,            -- hashed by Django
    last_login   TIMESTAMPTZ,
    is_superuser BOOLEAN      NOT NULL DEFAULT FALSE,
    username     VARCHAR(150) NOT NULL UNIQUE,
    first_name   VARCHAR(150) NOT NULL DEFAULT '',
    last_name    VARCHAR(150) NOT NULL DEFAULT '',
    email        VARCHAR(254) NOT NULL DEFAULT '',
    is_staff     BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
    date_joined  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    role         VARCHAR(16)  NOT NULL DEFAULT 'member'
);

CREATE TABLE workspace_workspace (
    id          UUID PRIMARY KEY,                  -- uuid4 generated by app
    created_by_id BIGINT NOT NULL REFERENCES authen_user(id) ON DELETE RESTRICT,
    name        VARCHAR(50)  NOT NULL DEFAULT 'Untitled Workspace',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX workspace_workspace_created_by_idx ON workspace_workspace (created_by_id);

CREATE TABLE workspace_workspacemember (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id UUID   NOT NULL REFERENCES workspace_workspace(id) ON DELETE CASCADE,
    user_id      BIGINT NOT NULL REFERENCES authen_user(id)         ON DELETE CASCADE,
    joined_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT workspace_member_unique UNIQUE (workspace_id, user_id)
);
CREATE INDEX workspace_member_user_idx ON workspace_workspacemember (user_id);

CREATE TABLE workspace_workspaceinvite (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id UUID   NOT NULL REFERENCES workspace_workspace(id) ON DELETE CASCADE,
    token        VARCHAR(64) NOT NULL UNIQUE,      -- secrets.token_urlsafe(32)
    created_by_id BIGINT NOT NULL REFERENCES authen_user(id) ON DELETE RESTRICT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ NOT NULL,
    max_uses     INTEGER NOT NULL DEFAULT 1 CHECK (max_uses >= 0),
    uses         INTEGER NOT NULL DEFAULT 0 CHECK (uses >= 0)
);
CREATE INDEX workspace_invite_workspace_idx ON workspace_workspaceinvite (workspace_id);

CREATE TABLE documents_document (
    id           UUID PRIMARY KEY,
    workspace_id UUID   NOT NULL REFERENCES workspace_workspace(id) ON DELETE CASCADE,
    owner_id     BIGINT NOT NULL REFERENCES authen_user(id)         ON DELETE RESTRICT,
    filename     VARCHAR(255) NOT NULL,
    mime         VARCHAR(100) NOT NULL,
    size_bytes   INTEGER NOT NULL CHECK (size_bytes >= 0),
    storage_key  VARCHAR(512) NOT NULL,            -- path in object/file storage
    status       VARCHAR(16)  NOT NULL DEFAULT 'pending',   -- pending | ready | failed
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    error        TEXT NOT NULL DEFAULT ''
);
CREATE INDEX documents_document_ws_owner_idx ON documents_document (workspace_id, owner_id);
CREATE INDEX documents_document_status_idx   ON documents_document (status);

CREATE TABLE documents_documentchunk (
    id          UUID PRIMARY KEY,
    document_id UUID NOT NULL REFERENCES documents_document(id) ON DELETE CASCADE,
    chunk_index INTEGER NOT NULL,
    content     TEXT NOT NULL,
    embedding   vector(1024) NOT NULL,
    CONSTRAINT documents_chunk_doc_index_unique UNIQUE (document_id, chunk_index)
);
CREATE INDEX documents_chunk_document_idx ON documents_documentchunk (document_id);

CREATE TABLE documents_request (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT NOT NULL REFERENCES authen_user(id)         ON DELETE RESTRICT,
    workspace_id          UUID   NOT NULL REFERENCES workspace_workspace(id) ON DELETE CASCADE,
    question              TEXT NOT NULL,
    answer                TEXT NOT NULL DEFAULT '',
    retrieved_chunk_ids   JSONB NOT NULL DEFAULT '[]',   -- soft refs; survive chunk deletion
    excluded_document_ids JSONB NOT NULL DEFAULT '[]',
    tokens_in             INTEGER NOT NULL DEFAULT 0 CHECK (tokens_in  >= 0),
    tokens_out            INTEGER NOT NULL DEFAULT 0 CHECK (tokens_out >= 0),
    status                VARCHAR(16) NOT NULL DEFAULT 'pending',  -- pending | success | failed | not_found
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX documents_request_user_idx      ON documents_request (user_id);
CREATE INDEX documents_request_workspace_idx ON documents_request (workspace_id);

CREATE TABLE documents_usageevent (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES authen_user(id)       ON DELETE RESTRICT,
    request_id  BIGINT NOT NULL REFERENCES documents_request(id) ON DELETE RESTRICT,
    tokens      INTEGER NOT NULL CHECK (tokens >= 0),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT documents_usage_one_per_request UNIQUE (request_id)  -- at most one usage row per request
);
CREATE INDEX documents_usageevent_user_idx ON documents_usageevent (user_id);

